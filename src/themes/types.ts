/**
 * Словарь оформления.
 *
 * Здесь описаны ВСЕ рычаги, которыми отличаются темы: плотность, форма
 * карточек, тип кнопок, ширина контейнера, раскладка первого экрана,
 * фон страницы (полотно, текстура, декор), форма фото-слота, шрифтовые
 * семейства и палитры. Само оформление живёт в двух местах:
 *
 *   src/styles/params.css        — как значение превращается в CSS
 *                                  (атрибут на <html> → набор переменных);
 *   src/themes/<id>/theme.css    — что тема добавляет своего: палитра,
 *                                  тени, декор, собственные правила.
 *
 * Такое разделение - главное условие задачи «много тем и маленький прод»:
 * параметры общие для всех тем и лежат в одном небольшом файле, а всё
 * специфичное для темы складывается в её собственный CSS, который в прод
 * попадает только если тема выбрана.
 */

import type { Locale } from '../i18n/config';
import type { Localized } from '../data/types';

/** Плотность блоков: масштабирует все внутренние отступы через --d. */
export type DensityKind = 'compact' | 'normal' | 'spacious';

/** Оформление карточек. */
export type CardKind =
  | 'flat'
  /** Тонкая линия в цвет темы — нейтральный «сервисный» вариант. */
  | 'outline'
  /** Мягкая тень — карточка «отрывается» от фона. */
  | 'shadow'
  /** Жёсткая рамка и сдвинутая тень — приём брутализма и зинов. */
  | 'hard'
  /** Наклейка: подложка, поворот и «мультяшная» тень — приём «милоты». */
  | 'sticker';

/** Оформление кнопок. */
export type ButtonKind =
  | 'solid'
  | 'soft'
  | 'outline'
  /** Редакционная ссылка: подчёркнутый капс без заливки — как в журналах. */
  | 'link'
  /** Плотный блок с жёсткой сдвинутой тенью — брутализм. */
  | 'hard';

/** Фоновая текстура страницы: тонкая графическая деталь, «не-ИИ» эффект. */
export type TextureKind =
  /** Чистый фон. */
  | 'none'
  /** Зерно/шум — ощущение печати на бумаге. */
  | 'grain'
  /** Точечная сетка — «милота» и мемфис. */
  | 'dots'
  /** Техническая сетка — «инженерный» стиль. */
  | 'grid'
  /** Концентрические волны от верхнего края — «водная» тема. */
  | 'waves'
  /** Наклонные полосы — тетрадный лист. */
  | 'stripes'
  /** Ряд полукругов — мягкий «чешуйчатый» край. */
  | 'scallops'
  /** Клетка в две косые линии — уютный текстиль. */
  | 'checks';

/** Идентификаторы палитр внутри тем. */
export type PaletteKind =
  | 'sky'
  | 'mist'
  | 'milk'
  | 'aqua'
  | 'rose'
  | 'peach'
  | 'butter'
  | 'lilac';

/**
 * Подложка страницы: как выглядит фон под содержимым.
 *
 * Текстура (TextureKind) рисует узор поверх, а поверхность отвечает за сам
 * «холст» — ровный, тонированный, с градиентом или с пятнами акцента.
 * Значения цветов остаются за палитрой: этот параметр только добавляет слои.
 */
export type SurfaceKind = 'flat' | 'tint' | 'gradient' | 'mesh';

/**
 * Декор страницы: мелкая графика поверх фона.
 *
 * Это самый «настроенческий» рычаг: пузырьки и искры делают страницу
 * игривой, не меняя ни одного блока разметки. Рисуется градиентами на
 * псевдоэлементе, поэтому не стоит ни одного запроса и работает без JS.
 */
export type DecorKind = 'none' | 'bubbles' | 'sparkles' | 'confetti' | 'ripples';

/** Форма фото-слота: чем снимок отличается по силуэту. */
export type PhotoShapeKind = 'rect' | 'arch' | 'round' | 'blob';

/** Обработка фотографий и фото-заглушек. */
export type PhotoKind =
  | 'plain'
  /** Двухцветная печать: снимок уходит в один тон темы. */
  | 'duotone'
  /** Растровая точка: журнальный/печатный приём. */
  | 'halftone';

/** Ширина контейнера. */
export type ContainerKind = 'normal' | 'wide';

/** Раскладка первого экрана. */
export type HeroKind = 'split' | 'center' | 'full';

/**
 * Ритм секций: как страница членится по вертикали.
 *
 * Это самый заметный признак «другой вёрстки»: одна и та же разметка с
 * `banded` выглядит как рекламная брошюра, с `editorial` — как журнал.
 */
export type SectionsKind =
  | 'plain'
  /** Полосы: каждая вторая секция на подложке. */
  | 'banded'
  /** Журнальная подача: нумерация секций и волосяные линейки. */
  | 'editorial';

/** Шрифтовые семейства. `system` — вариант без веб-шрифтов (ноль загрузки). */
export type FontKind = 'manrope' | 'lora' | 'playfair' | 'nunito' | 'comfortaa' | 'system';

/** Светлая или тёмная тема (влияет на color-scheme и заготовки под фото). */
export type ThemeKind = 'light' | 'dark';

/** Булев переключатель в виде строки — так он живёт в атрибутах и URL. */
export type SwitchKind = 'on' | 'off';

/**
 * Подсказка «заявка с расчётом» на закреплённой кнопке телефона.
 *
 * Когда посетитель что-то изменил в калькуляторе, ссылка на Telegram начинает
 * нести состав заказа. Чтобы это было заметно, кнопка меняет вид; варианты
 * отличаются ровно одним слоем — от смены текста до текста с иконкой,
 * свечением и бейджем. Выбирается в демо-панели, в прод уезжает один.
 */
export type OrderHintKind = 'text' | 'icon' | 'glow' | 'badge' | 'combo';

/** Схема раскладки — рисуется в паспорте темы в демо-панели. */
export type LayoutSketch = 'split' | 'center' | 'poster' | 'banded' | 'grid' | 'zigzag';

/** Адреса субсетов одного семейства: локаль → URL готового ассета. */
export type FontUrls = Record<Locale, string>;

/**
 * Точка входа темы для сборки (src/themes/entries/<id>.ts).
 *
 * Именно этот файл выбирается алиасом `@theme`: в прод-сборке он один,
 * в демо — `entries/all.ts` со всеми темами. Поэтому перечень шрифтов
 * здесь — это ещё и бюджет: сколько файлов шрифтов уедет в `dist/_a`.
 */
export interface ThemeEntry {
  id: string;
  /** Только те семейства, которые нужны теме: остальные в прод не попадут. */
  fonts: Partial<Record<FontKind, FontUrls>>;
}

/** Значения параметров по умолчанию для темы. */
export interface ThemeDefaults {
  radius: number;
  density: DensityKind;
  headingFont: FontKind;
  bodyFont: FontKind;
  card: CardKind;
  button: ButtonKind;
  container: ContainerKind;
  hero: HeroKind;
  sections: SectionsKind;
  texture: TextureKind;
  surface: SurfaceKind;
  decor: DecorKind;
  photo: PhotoKind;
  /**
   * Форма фото-слота. null — «как в базовом слое» (скругление --r-lg):
   * так живут темы, которые специально ничего не меняют.
   */
  photoShape: PhotoShapeKind | null;
  /** Палитра, с которой тема выглядит так, как её задумал автор. */
  palette: PaletteKind | null;
}

/** Описание темы для панели и для сборки. */
export interface ThemePreset {
  id: string;
  /** Локализованное название — заказчик видит его в панели на своём языке. */
  name: Localized;
  /** Одно предложение о том, какое ощущение создаёт тема. */
  description: Localized;
  kind: ThemeKind;
  /** Схема раскладки для мини-превью. */
  layout: LayoutSketch;
  defaults: ThemeDefaults;
  /**
   * Шрифты, которые тема допускает.
   *
   * Почему список, а не всё подряд: заказчик может поменять шрифт внутри
   * темы, но только на тот, который тема уже везёт с собой. Это держит
   * бюджет шрифтов предсказуемым: перечень из темы — это и есть тот
   * максимум woff2, который может попасть в прод-сборку.
   */
  available: {
    heading: FontKind[];
    body: FontKind[];
    /**
     * Палитры темы. Пустой список — тема живёт с одной палитрой, и группа
     * палитр в панели для неё не показывается. Цвета — в src/themes/tokens.ts,
     * свотчи для панели выводятся оттуда же (swatchOf), дублировать нечего.
     */
    palettes: PaletteKind[];
  };
}
