/**
 * Словарь оформления.
 *
 * Здесь описаны рычаги, которыми живёт оформление сайта: схема (светлая /
 * тёмная), шрифтовые семейства и точка входа темы. Конкретные значения
 * параметров (плотность, форма карточек, текстуры…) запечены в CSS:
 *   src/styles/params.css   — как значение превращается в CSS-переменные;
 *   src/themes/<id>/theme.css — что тема добавляет своего.
 *
 * Такое разделение — условие «маленький прод»: параметры лежат в одном
 * небольшом файле, а всё специфичное для темы — в её собственном CSS.
 */

import type { Locale } from '../i18n/config';
import type { Localized } from '../data/types';

/** Шрифтовые семейства. `system` — вариант без веб-шрифтов (ноль загрузки). */
export type FontKind = 'manrope' | 'lora' | 'system';

/** Светлая или тёмная схема (влияет на color-scheme и заготовки под фото). */
export type ThemeKind = 'light' | 'dark';

/** Адреса субсетов одного семейства: локаль → URL готового ассета. */
export type FontUrls = Record<Locale, string>;

/**
 * Точка входа темы для сборки (src/themes/entries/<id>.ts).
 *
 * Именно этот файл выбирается алиасом `@theme`, поэтому перечень шрифтов
 * здесь — это ещё и бюджет: сколько файлов шрифтов уедет в `dist/_a`.
 */
export interface ThemeEntry {
  id: string;
  /** Только те семейства, которые нужны теме: остальные в прод не попадут. */
  fonts: Partial<Record<FontKind, FontUrls>>;
}

/** Описание темы. */
export interface ThemePreset {
  id: string;
  /** Локализованное название темы. */
  name: Localized;
  /** Одно предложение о том, какое ощущение создаёт тема. */
  description: Localized;
  /** Натуральная схема: светлая по умолчанию или тёмная. */
  kind: ThemeKind;
  /**
   * Шрифты, которые тема допускает.
   *
   * Почему список, а не всё подряд: шрифт можно менять только на тот,
   * который тема уже везёт с собой. Это держит бюджет шрифтов предсказуемым:
   * перечень из темы — это и есть тот максимум woff2, который может
   * попасть в сборку.
   */
  available: {
    heading: FontKind[];
    body: FontKind[];
  };
}
